#!/usr/bin/env bash
# Generates the mechanical part of a batch's REPORT.md from run.log, DRIVER-NOTES.md and done.txt, so the driver
# writes only the judgement (findings, owner questions, improvement analysis) and the counts are not typed by hand
# (wave2-789 REPORT.md said 14 stops; run.log has 11 STOPPED lines and 12 restarts).
#
#   bash tools/batch-report.sh <batch-dir> [--out <file>] [--force]
#
# Writes <batch-dir>/REPORT.md (or --out); refuses to overwrite a file that exists unless --force, and prints it to stdout
# when --out is "-". Sections:
#   Counts      jobs, runner starts and restarts (`start at` lines; restarts = starts - 1), STOPPED lines (pauses counted
#               apart), HAND-FIX-EVENT lines, Sonnet share, the `full check:` line
#   Jobs        one table row per job: model, ladder, turns, minutes (usage row), wall minutes (start to finished line),
#               result, runs, failure class (a `<job> class: <capability|brief|gate|environment>` phrase in
#               DRIVER-NOTES.md), hand fix (lines changed, from HAND-FIX-EVENT lines). A row whose logged turns are under 3
#               while the job ran 5+ wall minutes is marked "resumed": the usage row covers the last resume only.
#   Metrics     tools/job-metrics.sh output when the script runs
# Exit codes: 0 written · 2 bad use or no run.log · 3 REPORT.md exists (use --force).
set -u
here="$(cd "$(dirname "$0")/.." && pwd)"
dir="" out="" force=0
while [ $# -gt 0 ]; do
  case "$1" in
    --out) out="${2:-}"; shift 2 || exit 2 ;;
    --force) force=1; shift ;;
    -*) echo "batch-report: unknown option $1" >&2; exit 2 ;;
    *) [ -z "$dir" ] && dir="${1%/}" || exit 2; shift ;;
  esac
done
[ -n "$dir" ] && [ -f "$dir/run.log" ] || { echo "batch-report: usage: batch-report.sh <batch-dir> [--out f] [--force] (needs <dir>/run.log)" >&2; exit 2; }
log="$dir/run.log"
notes="$dir/DRIVER-NOTES.md"
[ -n "$out" ] || out="$dir/REPORT.md"
if [ "$out" != - ] && [ -e "$out" ] && [ "$force" != 1 ]; then echo "batch-report: $out exists (use --force)" >&2; exit 3; fi

ts_epoch() { date -d "$1" +%s 2> /dev/null || echo 0; }
starts=$(grep -cE '^[0-9-]+ [0-9:]+ start at ' "$log")
stops=$(grep -cE '^[0-9-]+ [0-9:]+ STOPPED: ' "$log")
pauses=$(grep -cE '^[0-9-]+ [0-9:]+ STOPPED: PAUSED' "$log")
events=$(grep -c '^HAND-FIX-EVENT ' "$log")
fullcheck=$(grep '^full check:' "$log" | tail -n 1)
first_start=$(grep -E ' start at ' "$log" | head -n 1 | cut -c1-19)
last_ts=$(grep -E '^[0-9-]+ [0-9:]+ ' "$log" | tail -n 1 | cut -c1-19)
jobs=$(grep -E ' finished: result ' "$log" | sed -E 's/^[0-9-]+ [0-9:]+ ([^ ]+) finished.*/\1/' | awk '!s[$0]++')
njobs=$(printf '%s\n' "$jobs" | grep -c .)
nsonnet=0 nruns=0 nsonnet_runs=0

rows=""
for j in $jobs; do
  fin=$(grep -E "^[0-9-]+ [0-9:]+ $j finished: result " "$log" | tail -n 1)
  attempts=$(grep -cE "^[0-9-]+ [0-9:]+ $j finished: result " "$log")
  nruns=$((nruns + attempts))
  nsonnet_runs=$((nsonnet_runs + $(grep -E "^[0-9-]+ [0-9:]+ $j finished: result " "$log" | grep -c "model claude-sonnet" || true)))
  rc=$(sed -E 's/.* finished: result ([0-9]+).*/\1/' <<< "$fin")
  turns=$(sed -nE 's/.*\(([0-9]+) turns?, ([0-9]+) min\).*/\1/p' <<< "$fin")
  mins=$(sed -nE 's/.*\(([0-9]+) turns?, ([0-9]+) min\).*/\2/p' <<< "$fin")
  model=$(sed -nE 's/.* model ([^ ,]+),.*/\1/p' <<< "$fin")
  ladder=$(sed -nE 's/.* ladder ([0-9]+).*/\1/p' <<< "$fin")
  case "$model" in *sonnet*) nsonnet=$((nsonnet + 1)) ;; esac
  fts=$(cut -c1-19 <<< "$fin")
  sts=$(grep -E "^[0-9-]+ [0-9:]+ (start|resume) $j( |$)" "$log" | awk -v f="$fts" '$1" "$2 <= f' | tail -n 1 | cut -c1-19)
  wall="-"
  if [ -n "$sts" ]; then wall=$((($(ts_epoch "$fts") - $(ts_epoch "$sts")) / 60)); fi
  mark=""
  if [ "${turns:-99}" -lt 3 ] 2> /dev/null && [ "$wall" != - ] && [ "$wall" -ge 5 ]; then mark=" resumed (usage row = last resume only)"; fi
  class=$(grep -hoE "(^|[^A-Za-z0-9_-])$j class: (capability|brief|gate|environment)" "$notes" 2> /dev/null | tail -n 1 | sed -E 's/.*class: //')
  hand=$(grep -E "^HAND-FIX-EVENT ([A-Za-z0-9_ -]* )?$j( [A-Za-z0-9_-]+)*: " "$log" | sed -nE 's/.*: ([0-9]+) lines? (changed|moved).*/\1/p' | awk '{s+=$1;n++} END{if(n) printf "%d line(s), %d event(s)", s, n}')
  rows="$rows| $j | ${model:-?} | ${ladder:-?} | ${turns:-?} | ${mins:-?} | $wall | $rc | $attempts | ${class:--} | ${hand:--}$mark |"$'\n'
done

gen() {
  echo "# Report: $(basename "$dir") (generated by tools/batch-report.sh; the driver adds findings, owner questions and the analysis)"
  echo
  echo "## Counts"
  echo "- Runner starts $starts (restarts $((starts > 0 ? starts - 1 : 0))); STOPPED lines $stops, of which $pauses are pauses; HAND-FIX-EVENT lines $events."
  echo "- Jobs run $njobs; Sonnet briefs $nsonnet of $njobs$([ "$njobs" -gt 0 ] && echo " ($((nsonnet * 100 / njobs))%)"), runs $nsonnet_runs Sonnet of $nruns (a repair or resume is a second run of one brief); first start ${first_start:-?}, last log line ${last_ts:-?}."
  echo "- ${fullcheck:-full check: (none logged yet)}"
  echo
  echo "## Jobs"
  echo "| job | model | ladder | turns | min | wall min | result | runs | class | hand fix |"
  echo "|---|---|---|---|---|---|---|---|---|---|"
  printf '%s' "$rows"
  echo
  echo "## Metrics"
  if [ -f "$here/tools/job-metrics.sh" ]; then
    echo '```'
    bash "$here/tools/job-metrics.sh" "$dir" 2>&1 | head -n 60
    echo '```'
  else echo "(tools/job-metrics.sh not found)"; fi
}
if [ "$out" = - ]; then gen; else gen > "$out"; echo "batch-report: wrote $out ($njobs jobs, $stops STOPPED lines, $starts starts)"; fi

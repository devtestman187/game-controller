#!/usr/bin/env bash
# Turns the simulator CSV into the markdown tables of docs/briefs/m17/city/REPORT-v2.md (board3c).
#   bash tools/sim/tables.sh [csv] > docs/briefs/m17/city/sim-tables-v2.md
set -u
csv=${1:-docs/briefs/m17/city/sim-results-v2.csv}
[ -f "$csv" ] || { echo "no such csv: $csv" >&2; exit 1; }
echo "# Simulator tables v2 (generated by tools/sim/tables.sh from $(basename "$csv"))"
echo
echo "All shares in %. Plaza = the winner reached the Plaza. MidLast = last at the midpoint finishes not last. RW b/s/w = Roadworks user better/same/worse than the same night without Roadworks. Gated = mean place change of the gated player versus the same night with no gate (positive = worse) and the share that finished worse. MidLeader = the midpoint leader wins. Multi-gate = a road gated twice."
for pop in adult mixed; do
  for n in 2 3 4 5 6 7 8; do
    echo
    echo "## $pop bots, $n players, 5 games"
    echo
    echo "| Road | Roadworks | Plaza | MidLast | RW crews/night | RW b/s/w | Gated dPlace (worse) | MidLeader | Multi-gate |"
    echo "|---|---|---|---|---|---|---|---|---|"
    awk -F, -v p="$pop" -v n="$n" '
      NR > 1 && $1 == p && $2 == n && $8 == "false" && $9 == "true" {
        rw = ($20 == 0) ? "-" : sprintf("%.0f/%.0f/%.0f", $21 * 100, $22 * 100, $23 * 100)
        g = ($25 == 0) ? "-" : sprintf("%+.2f (%.0f)", $29, $28 * 100)
        printf "| %s | %s | %.1f | %.1f | %.2f | %s | %s | %.1f | %.1f |\n", $4, $7, $12 * 100, $18 * 100, $19, rw, g, $17 * 100, $30 * 100
      }' "$csv"
  done
done
echo
echo "## Adoption sensitivity: every adult bot always sends a crew when it can (gate on)"
echo
echo "| Players | Road | Roadworks | Plaza | MidLast | RW b/s/w |"
echo "|---|---|---|---|---|---|"
awk -F, 'NR > 1 && $8 == "true" { printf "| %s | %s | %s | %.1f | %.1f | %.0f/%.0f/%.0f |\n", $2, $4, $7, $12 * 100, $18 * 100, $21 * 100, $22 * 100, $23 * 100 }' "$csv"
echo
echo "## No-gate baseline (Roadworks off): Plaza, MidLast, MidLeader"
echo
echo "| Pop | Players | Road | Plaza | MidLast | MidLeader |"
echo "|---|---|---|---|---|---|"
awk -F, 'NR > 1 && $9 == "false" { printf "| %s | %s | %s | %.1f | %.1f | %.1f |\n", $1, $2, $4, $12 * 100, $18 * 100, $17 * 100 }' "$csv"
